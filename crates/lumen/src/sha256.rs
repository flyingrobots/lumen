/// Initial hash value: the first 32 bits of the fractional parts of the square roots of the
/// first 8 primes.
const H0: [u32; 8] = [
    0x6a09_e667,
    0xbb67_ae85,
    0x3c6e_f372,
    0xa54f_f53a,
    0x510e_527f,
    0x9b05_688c,
    0x1f83_d9ab,
    0x5be0_cd19,
];

/// An incremental SHA-256 computation.
#[derive(Clone, Debug)]
pub struct Sha256 {
    state: [u32; 8],
    block: [u8; 64],
    filled: usize,
    length_bits: u64,
}

impl Default for Sha256 {
    fn default() -> Self {
        Self::new()
    }
}

impl Sha256 {
    /// A computation over no bytes yet.
    #[must_use]
    pub const fn new() -> Self {
        Self { state: H0, block: [0; 64], filled: 0, length_bits: 0 }
    }

    /// Adds `bytes` to the message.
    pub fn update(&mut self, mut bytes: &[u8]) {
        // The message length is taken modulo 2^64 bits, as the standard specifies.
        self.length_bits = self.length_bits.wrapping_add((bytes.len() as u64).wrapping_mul(8));
        while !bytes.is_empty() {
            let take = (64 - self.filled).min(bytes.len());
            let (head, rest) = bytes.split_at(take);
            self.block[self.filled..self.filled + take].copy_from_slice(head);
            self.filled += take;
            bytes = rest;
            if self.filled == 64 {
                compress(&mut self.state, &self.block);
                self.filled = 0;
            }
        }
    }

    /// The digest of every byte added.
    #[must_use]
    pub fn finish(mut self) -> [u8; 32] {
        let length = self.length_bits;
        // Padding: one bit, zeros up to 56 bytes modulo 64, then the 64-bit big-endian length.
        let mut padding = [0_u8; 72];
        padding[0] = 0x80;
        let zeros = (119 - self.filled) % 64;
        let pad_len = 1 + zeros;
        padding[pad_len..pad_len + 8].copy_from_slice(&length.to_be_bytes());
        self.update(&padding[..pad_len + 8]);
        debug_assert_eq!(self.filled, 0);
        let mut digest = [0_u8; 32];
        for (out, word) in digest.chunks_exact_mut(4).zip(self.state) {
            out.copy_from_slice(&word.to_be_bytes());
        }
        digest
    }
}

/// One application of the compression function to a 64-byte block.
#[allow(clippy::many_single_char_names, reason = "the names of FIPS 180-4, section 6.2.2")]
fn compress(state: &mut [u32; 8], block: &[u8; 64]) {
    let mut w = [0_u32; 64];
    for (word, bytes) in w.iter_mut().zip(block.chunks_exact(4)) {
        *word = u32::from_be_bytes([bytes[0], bytes[1], bytes[2], bytes[3]]);
    }
    for t in 16..64 {
        let s0 = w[t - 15].rotate_right(7) ^ w[t - 15].rotate_right(18) ^ (w[t - 15] >> 3);
        let s1 = w[t - 2].rotate_right(17) ^ w[t - 2].rotate_right(19) ^ (w[t - 2] >> 10);
        w[t] = w[t - 16].wrapping_add(s0).wrapping_add(w[t - 7]).wrapping_add(s1);
    }
    let [mut a, mut b, mut c, mut d, mut e, mut f, mut g, mut h] = *state;
    for (k, w) in K.iter().zip(w) {
        let s1 = e.rotate_right(6) ^ e.rotate_right(11) ^ e.rotate_right(25);
        let ch = (e & f) ^ (!e & g);
        let t1 = h.wrapping_add(s1).wrapping_add(ch).wrapping_add(*k).wrapping_add(w);
        let s0 = a.rotate_right(2) ^ a.rotate_right(13) ^ a.rotate_right(22);
        let maj = (a & b) ^ (a & c) ^ (b & c);
        let t2 = s0.wrapping_add(maj);
        h = g;
        g = f;
        f = e;
        e = d.wrapping_add(t1);
        d = c;
        c = b;
        b = a;
        a = t1.wrapping_add(t2);
    }
    for (word, add) in state.iter_mut().zip([a, b, c, d, e, f, g, h]) {
        *word = word.wrapping_add(add);
    }
}

/// The SHA-256 digest of `bytes`.
#[must_use]
pub fn digest(bytes: &[u8]) -> [u8; 32] {
    let mut hasher = Sha256::new();
    hasher.update(bytes);
    hasher.finish()
}

/// Lowercase hexadecimal of `bytes`.
#[must_use]
pub fn hex(bytes: &[u8]) -> String {
    const DIGITS: &[u8; 16] = b"0123456789abcdef";
    let mut text = String::with_capacity(bytes.len() * 2);
    for byte in bytes {
        text.push(char::from(DIGITS[usize::from(byte >> 4)]));
        text.push(char::from(DIGITS[usize::from(byte & 0x0f)]));
    }
    text
}

#[cfg(test)]
mod tests {
    use super::*;

    fn sha(bytes: &[u8]) -> String {
        hex(&digest(bytes))
    }

    /// The examples of FIPS 180-2 (Appendix B) and NIST's SHA-256 example values.
    #[test]
    fn published_test_vectors() {
        assert_eq!(sha(b""), "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855");
        assert_eq!(sha(b"abc"), "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad");
        assert_eq!(
            sha(b"abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq"),
            "248d6a61d20638b8e5c026930c3e6039a33ce45964ff2167f6ecedd419db06c1"
        );
        assert_eq!(
            sha(&vec![b'a'; 1_000_000]),
            "cdc76e5c9914fb9281a1c7e284d73e67f1809a48a497200e046d39ccc7112cd0"
        );
    }

    /// Digests of `a` repeated around the padding boundaries (55, 56, 63, 64 and 65 bytes, and
    /// 119 and 120), from Python's `hashlib`, an independent implementation.
    #[test]
    fn padding_boundaries_match_an_independent_implementation() {
        let cases: [(usize, &str); 7] = [
            (55, "9f4390f8d30c2dd92ec9f095b65e2b9ae9b0a925a5258e241c9f1e910f734318"),
            (56, "b35439a4ac6f0948b6d6f9e3c6af0f5f590ce20f1bde7090ef7970686ec6738a"),
            (63, "7d3e74a05d7db15bce4ad9ec0658ea98e3f06eeecf16b4c6fff2da457ddc2f34"),
            (64, "ffe054fe7ae0cb6dc65c3af9b61d5209f439851db43d0ba5997337df154668eb"),
            (65, "635361c48bb9eab14198e76ea8ab7f1a41685d6ad62aa9146d301d4f17eb0ae0"),
            (119, "31eba51c313a5c08226adf18d4a359cfdfd8d2e816b13f4af952f7ea6584dcfb"),
            (120, "2f3d335432c70b580af0e8e1b3674a7c020d683aa5f73aaaedfdc55af904c21c"),
        ];
        for (len, want) in cases {
            assert_eq!(sha(&vec![b'a'; len]), want, "length {len}");
        }
    }

    #[test]
    fn split_updates_equal_one_update() {
        let message: Vec<u8> = (0..=255).cycle().take(1000).collect();
        let whole = digest(&message);
        for split in [0, 1, 63, 64, 65, 500, 999, 1000] {
            let mut hasher = Sha256::new();
            hasher.update(&message[..split]);
            hasher.update(&message[split..]);
            assert_eq!(hasher.finish(), whole, "split at {split}");
        }
    }
}
